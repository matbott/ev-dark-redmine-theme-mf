/* Ev Dark - Redmine theme (offline).
   Icon labels for icon-only menu links, clickable logo, and colour schemes
   (GoGogh curated palettes). Auto-loaded by Redmine's heads_for_theme in <head>.

   IMPORTANT: the early dark-mode block runs SYNCHRONOUSLY so the
   html.dark-mode class is set before the body renders - no flash. */

(function () {
  var stored = localStorage.getItem('rm-dark');
  var prefersDark = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches;
  if (stored === null) stored = '1'; // Ev Dark is a dark theme by default
  if (stored === '1' || (stored === null && prefersDark)) document.documentElement.classList.add('dark-mode');
  var scheme = localStorage.getItem('rm-scheme');
  if (scheme) document.documentElement.setAttribute('data-scheme', scheme);
})();

(function () {
  'use strict';

  var qs  = function (sel, ctx) { return (ctx || document).querySelector(sel); };
  var qsa = function (sel, ctx) { return Array.from((ctx || document).querySelectorAll(sel)); };

  /* ── I18N ─────────────────────────────────────────────────── */
  var I18N = {
    en: {
      colourScheme: 'Colour scheme',
      toggleDarkMode: 'Toggle dark mode',
      darkMode: 'Dark mode',
      lightMode: 'Light mode',
      defaultGroup: 'Default',
      darkGroup: 'Dark',
      lightGroup: 'Light',
      schemesGroupAria: '{g} colour schemes',
      noColorMix: 'This browser does not support colour schemes (needs CSS color-mix()).',
      schemesHint: 'Applies immediately and is saved in this browser only, separately for dark and light mode. Palettes from Gogh (github.com/Gogh-Co/Gogh).'
    },
    es: {
      colourScheme: 'Esquema de color',
      toggleDarkMode: 'Cambiar modo oscuro',
      darkMode: 'Modo oscuro',
      lightMode: 'Modo claro',
      defaultGroup: 'Predeterminado',
      darkGroup: 'Oscuros',
      lightGroup: 'Claros',
      schemesGroupAria: 'Esquemas de color: {g}',
      noColorMix: 'Este navegador no admite esquemas de color (necesita CSS color-mix()).',
      schemesHint: 'Se aplica al instante y se guarda solo en este navegador, por separado para modo oscuro y claro. Paletas de Gogh (github.com/Gogh-Co/Gogh).'
    }
  };
  var LANG = (document.documentElement.lang || 'en').slice(0, 2).toLowerCase();
  function t(key, vars) {
    var s = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
    if (vars) Object.keys(vars).forEach(function (k) { s = s.replace('{' + k + '}', vars[k]); });
    return s;
  }

  /* ── ICON LABELS + LOGO LINK ───────────────────────────────── */
  function highlightNavLabels() {
    document.querySelectorAll('#main-menu > ul > li > a, #top-menu li a').forEach(function (a) {
      var label = a.textContent.trim();
      if (label === '+') label = 'New';
      if (label) { a.setAttribute('data-label', label); a.removeAttribute('title'); }
    });
  }

  function buildLogoLink() {
    var rtl = document.documentElement.getAttribute('dir') === 'rtl';
    var logoLink = document.createElement('a');
    logoLink.href = '/';
    logoLink.title = 'Home';
    logoLink.setAttribute('aria-label', 'Home');
    logoLink.style.cssText =
      'position:fixed;top:12px;' + (rtl ? 'right:12px;' : 'left:12px;') +
      'width:32px;height:32px;z-index:41;display:block;border-radius:8px;' +
      'text-indent:-9999px;overflow:hidden;';
    document.body.appendChild(logoLink);
  }

  /* ── COLOUR SCHEMES ───────────────────────────────────────── */
  var SCHEMES = [
    { id: '', name: 'Ev Dark', dark: true, swatch: ['#1B1D31', '#D9DBF0', '#7B68EE'] },
    // @schemes:begin — generated by src/gen-schemes.py, do not edit
    { id: 'dracula', name: 'Dracula', dark: true, swatch: ['#282A36', '#F8F8F2', '#C098F9'] },
    { id: 'nord', name: 'Nord', dark: true, swatch: ['#2E3440', '#D8DEE9', '#88C0D0'] },
    { id: 'gruvbox-dark', name: 'Gruvbox Dark', dark: true, swatch: ['#282828', '#EBDBB2', '#D79921'] },
    { id: 'tokyo-night', name: 'Tokyo Night', dark: true, swatch: ['#1A1B26', '#C0CAF5', '#7AA2F7'] },
    { id: 'catppuccin-mocha', name: 'Catppuccin Mocha', dark: true, swatch: ['#1E1E2E', '#CDD6F4', '#89B4FA'] },
    { id: 'one-dark', name: 'One Dark', dark: true, swatch: ['#282C34', '#CDD1D9', '#61AFEF'] },
    { id: 'everforest-dark', name: 'Everforest Dark', dark: true, swatch: ['#2D353B', '#E5DDCC', '#85BEB7'] },
    { id: 'ros-pine', name: 'Rosé Pine', dark: true, swatch: ['#191724', '#E0DEF4', '#C4A7E7'] },
    { id: 'solarized-light', name: 'Solarized Light', dark: false, swatch: ['#FCF4DC', '#42535A', '#1F70BD'] },
    { id: 'gruvbox-light', name: 'Gruvbox Light', dark: false, swatch: ['#FBF1C7', '#3C3836', '#3B7174'] },
    { id: 'one-dark-pro', name: 'One Dark Pro', dark: true, swatch: ['#282C34', '#ABB2BF', '#61AFEF'] },
    { id: 'catppuccin-macchiato', name: 'Catppuccin Macchiato', dark: true, swatch: ['#24273A', '#CAD3F5', '#8AADF4'] },
    { id: 'github-dark', name: 'GitHub Dark', dark: true, swatch: ['#101216', '#E6EDF3', '#58A6FF'] },
    { id: 'kanagawa-wave', name: 'Kanagawa Wave', dark: true, swatch: ['#1F1F28', '#DCD7BA', '#7E9CD8'] },
    { id: 'monokai-pro', name: 'Monokai Pro', dark: true, swatch: ['#2D2A2E', '#FCFCFA', '#FC9867'] },
    { id: 'ayu-dark', name: 'Ayu Dark', dark: true, swatch: ['#0A0E14', '#B3B1AD', '#59C2FF'] },
    // @schemes:end
  ];
  var RECENT_MAX = 4;
  var RECENT_DEFAULT = ['', 'dracula', 'nord', 'gruvbox-dark'];

  function findScheme(id) {
    return SCHEMES.filter(function (s) { return s.id === id; })[0] || SCHEMES[0];
  }
  function schemesSupported() {
    return !!(window.CSS && CSS.supports('color', 'color-mix(in srgb, red, white)'));
  }
  function currentSchemeId() {
    return document.documentElement.getAttribute('data-scheme') || '';
  }
  function recentSchemeIds() {
    var ids = null;
    try { ids = JSON.parse(localStorage.getItem('rm-scheme-recent')); } catch (e) {}
    if (!Array.isArray(ids)) ids = RECENT_DEFAULT;
    var out = [];
    [currentSchemeId()].concat(ids, RECENT_DEFAULT).forEach(function (id) {
      if (out.length < RECENT_MAX && out.indexOf(id) === -1 && findScheme(id)) out.push(id);
    });
    return out;
  }
  function rememberScheme(id) {
    var ids = [id].concat(recentSchemeIds().filter(function (x) { return x !== id; }));
    try { localStorage.setItem('rm-scheme-recent', JSON.stringify(ids.slice(0, RECENT_MAX))); } catch (e) {}
  }
  function modeKey(dark) { return dark ? 'dark' : 'light'; }
  function rememberModeScheme(dark, scheme) {
    if (!scheme) return;
    try {
      localStorage.setItem('rm-scheme-' + modeKey(dark), scheme.id);
    } catch (e) {}
  }
  function modeScheme(dark) {
    var id = localStorage.getItem('rm-scheme-' + modeKey(dark)) || '';
    var scheme = findScheme(id);
    if (scheme && (scheme.dark === null || scheme.dark === undefined || scheme.dark === dark)) return scheme;
    return SCHEMES[0];
  }
  function applyScheme(id) {
    var root = document.documentElement;
    var scheme = findScheme(id) || SCHEMES[0];
    if (scheme.id) { root.setAttribute('data-scheme', scheme.id); try { localStorage.setItem('rm-scheme', scheme.id); } catch (e) {} }
    else { root.removeAttribute('data-scheme'); try { localStorage.removeItem('rm-scheme'); } catch (e) {} }
    if (scheme.dark !== null && scheme.dark !== undefined) {
      root.classList.toggle('dark-mode', scheme.dark);
      try { localStorage.setItem('rm-dark', scheme.dark ? '1' : '0'); } catch (e) {}
    }
    rememberModeScheme(root.classList.contains('dark-mode'), scheme);
    rememberScheme(scheme.id);
    var menu = qs('#rm-scheme-menu');
    if (menu) renderSchemeMenu();
  }

  /* ── TOP BAR: colour scheme dropdown ──────────────────────── */
  var themeWrap = null, themeBtn = null, themeMenu = null;

  function buildThemeControls() {
    if (themeWrap) return;
    var top = qs('#top-menu');
    if (!top) return;
    var li = document.createElement('li');
    li.id = 'rm-scheme-wrap';
    var btn = document.createElement('button');
    btn.id = 'rm-scheme-trigger';
    btn.type = 'button';
    btn.setAttribute('aria-haspopup', 'menu');
    btn.setAttribute('aria-expanded', 'false');
    btn.title = t('colourScheme');
    btn.className = 'rm-scheme-trigger';
    var glyph = document.createElement('span');
    glyph.className = 'rm-scheme-glyph';
    glyph.textContent = '🎨';
    btn.appendChild(glyph);
    var dd = document.createElement('div');
    dd.id = 'rm-scheme-menu';
    dd.className = 'rm-scheme-menu';
    dd.setAttribute('role', 'menu');
    li.appendChild(btn);
    li.appendChild(dd);
    top.appendChild(li);
    themeWrap = li; themeBtn = btn; themeMenu = dd;
    btn.addEventListener('click', function (e) {
      e.stopPropagation();
      var open = themeMenu.classList.toggle('open');
      themeBtn.setAttribute('aria-expanded', open ? 'true' : 'false');
      if (open) renderSchemeMenu();
    });
  }

  function closeThemeMenu() {
    if (themeMenu) { themeMenu.classList.remove('open'); if (themeBtn) themeBtn.setAttribute('aria-expanded', 'false'); }
  }
  document.addEventListener('click', function (e) {
    if (themeWrap && !themeWrap.contains(e.target)) closeThemeMenu();
  });

  function renderSchemeMenu() {
    if (!themeMenu) return;
    themeMenu.innerHTML = '';
    var head = document.createElement('div');
    head.className = 'rm-scheme-head';
    head.textContent = t('colourScheme');
    themeMenu.appendChild(head);
    var isDark = document.documentElement.classList.contains('dark-mode');
    var list = SCHEMES.filter(function (s) { return isDark ? s.dark !== false : s.dark === false; });
    list.forEach(function (s) {
      var opt = document.createElement('button');
      opt.type = 'button';
      opt.className = 'rm-scheme-opt' + (s.id === currentSchemeId() ? ' selected' : '');
      opt.setAttribute('data-scheme-id', s.id);
      var dot = document.createElement('span');
      dot.className = 'rm-scheme-dot';
      dot.style.background = 'linear-gradient(135deg, ' + s.swatch[0] + ' 50%, ' + s.swatch[2] + ' 50%)';
      var name = document.createElement('span');
      name.className = 'rm-scheme-name';
      name.textContent = s.name;
      opt.appendChild(dot);
      opt.appendChild(name);
      opt.addEventListener('click', function () { applyScheme(s.id); closeThemeMenu(); });
      themeMenu.appendChild(opt);
    });
    var toggle = document.createElement('button');
    toggle.type = 'button';
    toggle.className = 'rm-scheme-opt';
    toggle.addEventListener('click', function () {
      var scheme = modeScheme(!document.documentElement.classList.contains('dark-mode'));
      applyScheme(scheme.id);
      closeThemeMenu();
    });
    var toggleName = document.createElement('span');
    toggleName.className = 'rm-scheme-name';
    toggleName.textContent = document.documentElement.classList.contains('dark-mode') ? t('lightMode') : t('darkMode');
    toggle.appendChild(toggleName);
    themeMenu.appendChild(toggle);
  }

  /* ── MY ACCOUNT: full colour scheme picker ────────────────── */
  function initSchemeSettings() {
    if (!document.body.classList.contains('controller-my')) return;
    if (!document.body.classList.contains('action-account')) return;
    if (qs('#rm-schemes')) return;
    var prefs = qs('#pref_comments_sorting');
    var prefsBox = prefs && prefs.closest('fieldset');
    if (!prefsBox) return;

    var box = document.createElement('fieldset');
    box.className = 'box';
    box.id = 'rm-schemes';
    var legend = document.createElement('legend');
    legend.textContent = t('colourScheme');
    box.appendChild(legend);

    if (schemesSupported()) {
      [[t('defaultGroup'), null], [t('darkGroup'), true], [t('lightGroup'), false]].forEach(function (g) {
        var list = SCHEMES.filter(function (s) { return g[1] === null ? s.id === '' : s.dark === g[1]; });
        if (!list.length) return;
        var head = document.createElement('div');
        head.className = 'rm-scheme-group';
        head.textContent = g[0];
        var grid = document.createElement('div');
        grid.className = 'rm-scheme-grid';
        grid.setAttribute('role', 'radiogroup');
        grid.setAttribute('aria-label', t('schemesGroupAria', { g: g[0] }));
        list.forEach(function (s) {
          var card = document.createElement('button');
          card.type = 'button';
          card.className = 'rm-scheme-card' + (s.id === currentSchemeId() ? ' selected' : '');
          card.setAttribute('data-scheme-id', s.id);
          card.setAttribute('role', 'radio');
          card.setAttribute('aria-checked', s.id === currentSchemeId() ? 'true' : 'false');
          var dot = document.createElement('span');
          dot.className = 'rm-scheme-dot';
          dot.style.background = 'linear-gradient(135deg, ' + s.swatch[0] + ' 50%, ' + s.swatch[2] + ' 50%)';
          var name = document.createElement('span');
          name.className = 'rm-scheme-name';
          name.textContent = s.name;
          card.appendChild(dot);
          card.appendChild(name);
          card.addEventListener('click', function () { applyScheme(s.id); });
          grid.appendChild(card);
        });
        box.appendChild(head);
        box.appendChild(grid);
      });
      var hint = document.createElement('p');
      hint.className = 'rm-scheme-hint';
      hint.textContent = t('schemesHint');
      box.appendChild(hint);
    }
    prefsBox.parentNode.insertBefore(box, prefsBox.nextSibling);
    if (location.hash === '#rm-schemes') box.scrollIntoView();
  }

  /* ── INIT ─────────────────────────────────────────────────── */
  function init() {
    highlightNavLabels();
    buildLogoLink();
    buildThemeControls();
    initSchemeSettings();
    applyScheme(currentSchemeId());
  }

  document.addEventListener('DOMContentLoaded', function () {
    init();
  });
})();
